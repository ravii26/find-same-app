# app/sources/huawei_adapter.py
"""Huawei AppGallery adapter — Playwright, no credentials.

Huawei's web backend rejects direct HTTP calls (it expects a token generated by its own
JavaScript), so the search page is loaded in headless Chromium and the JSON the page itself
fetches for the search (``getTabDetail`` with ``uri=searchApp|<term>``) is read from the
network. Search is fuzzy — "phonepe" also returns generic "Phone …" apps — so results are
filtered to those whose name or package mentions the brand.

Search URL: https://appgallery.huawei.com/search/{term}
App page:   https://appgallery.huawei.com/app/{appid}
"""

from __future__ import annotations

import asyncio
import datetime
import hashlib
import logging
from urllib.parse import quote, unquote

from app.api.models import (
    FoundVia,
    Hit,
    HitType,
    HostInfo,
    ScanContext,
    SourceMethod,
    SourceStatus,
)
from app.services.keyword_expansion import fold_homoglyphs
from app.sources.base import SourceAdapter

from app.utils.http_client import throttle

log = logging.getLogger(__name__)

try:
    from playwright.async_api import async_playwright as _async_playwright
    _PLAYWRIGHT_OK = True
except ImportError:
    _async_playwright = None  # type: ignore[assignment]
    _PLAYWRIGHT_OK = False

_SEARCH_PAGE = "https://appgallery.huawei.com/search/{q}"

_UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
    "AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
)

_RESPONSE_TIMEOUT_S = 25
_MAX_TERMS = 2  # each term is a full browser page load


def _is_search_response(url: str) -> bool:
    return "getTabDetail" in url and "searchApp" in unquote(url)


def _extract_apps(payload: object) -> list[dict]:
    """App items are dicts carrying both 'package' and 'name', nested anywhere in the payload."""
    found: list[dict] = []

    def walk(o: object) -> None:
        if isinstance(o, dict):
            if "package" in o and "name" in o:
                found.append(o)
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)

    walk(payload)
    return found


class HuaweiAdapter(SourceAdapter):
    name = "huawei_appgallery"
    method = SourceMethod.scrape
    host_group = "app_store"
    max_results = 10  # official store — expect 1 official app + a few lookalikes

    async def search(self, ctx: ScanContext) -> tuple[list[Hit], SourceStatus]:
        if not _PLAYWRIGHT_OK:
            return [], SourceStatus(
                name=self.name, method=self.method, status="failed",
                error="playwright not installed — run: pip install playwright && playwright install chromium",
            )

        brand_tokens = {t.lower() for t in fold_homoglyphs(ctx.request.brand_name).split() if len(t) >= 3}
        terms = [
            kw.term for kw in ctx.expanded_keywords
            if kw.type.value in ("original", "package")
            and any(tok in kw.term.lower() for tok in brand_tokens)
        ][:_MAX_TERMS] or [ctx.request.brand_name]

        hits: list[Hit] = []
        seen: set[str] = set()
        errors: list[str] = []

        try:
            async with _async_playwright() as p:
                browser = await p.chromium.launch(
                    headless=True,
                    args=["--no-sandbox", "--disable-dev-shm-usage", "--disable-gpu"],
                )
                bctx = await browser.new_context(
                    accept_downloads=False,
                    user_agent=_UA, locale="en-US", viewport={"width": 1280, "height": 900},
                )
                for term in terms:
                    page = await bctx.new_page()
                    captured: asyncio.Future = asyncio.get_running_loop().create_future()

                    async def on_response(resp, _fut=captured) -> None:
                        if _fut.done() or not _is_search_response(resp.url):
                            return
                        try:
                            _fut.set_result(await resp.json())
                        except Exception as e:
                            _fut.set_exception(e)

                    page.on("response", lambda r, _h=on_response: asyncio.ensure_future(_h(r)))
                    try:
                        await throttle(_SEARCH_PAGE.format(q=quote(term)))
                        await page.goto(
                            _SEARCH_PAGE.format(q=quote(term)),
                            wait_until="domcontentloaded", timeout=45000,
                        )
                        payload = await asyncio.wait_for(captured, _RESPONSE_TIMEOUT_S)
                    except Exception as e:
                        log.warning("huawei_appgallery: search failed for %r: %s", term, e)
                        errors.append(f"{type(e).__name__}: {e}")
                        continue
                    finally:
                        await page.close()

                    for item in _extract_apps(payload):
                        hit = self._to_hit(item, term, brand_tokens, ctx, seen)
                        if hit:
                            hits.append(hit)
                await browser.close()
        except Exception as exc:
            log.warning("huawei_appgallery: scrape failed: %s", exc)
            return [], SourceStatus(
                name=self.name, method=self.method, status="failed",
                error=f"Playwright error: {exc}",
            )

        if errors and not hits:
            status_val, err_msg = "failed", errors[0]
        elif errors:
            status_val, err_msg = "partial", errors[0]
        else:
            status_val, err_msg = "ok", None
        return hits, SourceStatus(
            name=self.name, method=self.method, status=status_val,
            results=len(hits), error=err_msg,
        )

    def _to_hit(
        self, item: dict, term: str, brand_tokens: set[str], ctx: ScanContext, seen: set[str],
    ) -> Hit | None:
        pkg = item.get("package") or ""
        name = (item.get("name") or "").strip()
        app_id = item.get("appid") or ""
        if not pkg or not name:
            return None

        name_lower = fold_homoglyphs(name).lower()
        if brand_tokens and not (
            any(tok in name_lower for tok in brand_tokens)
            or any(tok in pkg.lower() for tok in brand_tokens)
        ):
            return None

        url = f"https://appgallery.huawei.com/app/{app_id or pkg}"
        uid = hashlib.sha256(url.encode()).hexdigest()[:32]
        if uid in seen:
            return None
        seen.add(uid)

        return Hit(
            id=uid,
            type=HitType.app_listing,
            title=name,
            app_name=name,
            package_id=pkg,
            version=item.get("appVersionName") or None,
            icon_url=item.get("icon") or None,
            url=url,
            host=HostInfo(
                group=self.host_group,
                name="Huawei AppGallery",
                domain="appgallery.huawei.com",
                is_official_store=True,
            ),
            found_via=[FoundVia(source=self.name, method=self.method, query=term)],
            relevance_score=0,
            discovered_at=datetime.datetime.now(datetime.timezone.utc),
        )
